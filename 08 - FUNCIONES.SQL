-- FUNCION PARA RETORNAR EL CUADRADO DE UN NUMERO

CREATE OR REPLACE FUNCTION calcular_cuadrado_de_un_numero(
    P_NUMERO IN NUMBER

) RETURN NUMBER --ESTO ES SOLO EL TIPO DE RETORNO, NO ESTÁ RETORNANDO LA FUNCION
IS
    --ACÁ SE PUEDEN DECLARAR VARIABLES
    V_RESLATADO NUMBER;

BEGIN
    V_RESLATADO := P_NUMERO * P_NUMERO;
    RETURN V_RESLATADO; --AWUÍ SI RETORNA LA FUNCIÓN 

END calcular_cuadrado_de_un_numero;
/





-- LAS FUNCIONES PUEDEN OCUPARSE DENTRO DE UN SELECT A DIFERENCIA DE LOS PROCEDIMIENTOS (LA TABLA DUAL LA OCUPAMOS EN ESTE CASO PARA HACER PRUEBAS)
SELECT calcular_cuadrado_de_un_numero (5) 
AS CUADRADO FROM DUAL;


