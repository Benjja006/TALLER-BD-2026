CREATE OR REPLACE FUNCTION DESCUENTO_BANCO (
    P_ID_BANCO IN NUMBER,
    P_PRECIO_ENTRADA IN NUMBER
) RETURN NUMBER
IS
    V_PORCENTAJE_DESCUENTO NUMBER;
    V_PRECIO_FINAL_ENTRADA NUMBER;
BEGIN 
    SELECT DESCUENTO_PORCENTAJE
    INTO V_PORCENTAJE_DESCUENTO 
    FROM CONVENIO_BANCO
    WHERE CONVENIO_BANCO_ID = P_ID_BANCO AND ACTIVO = 'S';

    V_PRECIO_FINAL_ENTRADA := P_PRECIO_ENTRADA - (P_PRECIO_ENTRADA * V_PORCENTAJE_DESCUENTO )/ 100;
    RETURN V_PRECIO_FINAL_ENTRADA;
END DESCUENTO_BANCO;


/

