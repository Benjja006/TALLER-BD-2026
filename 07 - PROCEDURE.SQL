-- 1.0 PRODECIMIENTO PARA INSERTAR CLIENTES (CON DATOS DE ENTRADA)
CREATE OR REPLACE PROCEDURE registrar_cliente(
    P_RUT IN VARCHAR2, 
    P_NOMBRE IN VARCHAR2,
    P_APELLIDO IN VARCHAR2,
    P_EMAIL IN VARCHAR2,
    P_TELEFONO IN VARCHAR2
) 
AS

BEGIN 
    INSERT INTO CLIENTE (
        RUT, 
        NOMBRE,
        APELLIDO,
        EMAIL,
        TELEFONO)

    VALUES(
        P_RUT,
        P_NOMBRE,
        P_APELLIDO,
        P_EMAIL,
        P_TELEFONO
    );
    COMMIT;

    DBMS_OUTPUT.PUT_LINE('USUARIO' || P_NOMBRE ||'REGISTRADO CORRECTAMENTE');
END registrar_cliente;

/

--CREAR UN PROCEDIMIENTO ALMACENADO QUE DEVUELVA LOS DATOS DE UN CLIENTE SEGUN SU ID / (ESTE PROCEDIMIENTO OCUPA PARANETROS DE ENTRASA (IS) Y DE SALIDA (OUT))

CREATE OR REPLACE PROCEDURE datos_cliente(
    --PARAMETRO DE ENTRDA
    P_ID IN NUMBER,

    --PARAMETRO DE SALIDA
    P_RUT OUT VARCHAR2, 
    P_NOMBRE OUT VARCHAR2,
    P_APELLIDO OUT VARCHAR2,
    P_EMAIL OUT VARCHAR2,
    P_TELEFONO OUT VARCHAR2
)
AS

BEGIN
    SELECT 
        RUT,
        NOMBRE,
        APELLIDO,
        EMAIL,
        TELEFONO
    INTO P_RUT, P_NOMBRE,P_APELLIDO,P_EMAIL,P_TELEFONO
    FROM CLIENTE 
    WHERE CLIENTE_ID = P_ID;

END datos_cliente; --SEIMPRE SE TERMINA CON EL NOMBRE DEL PRODECIMIENTO
