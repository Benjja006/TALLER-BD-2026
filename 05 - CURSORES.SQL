
DECLARE

    CURSOR C_CLIENTES IS 
        SELECT * FROM CLIENTE;

    V_CONTADOR NUMBER:= 1;
BEGIN
    FOR POR_CADA_CLIENTE IN C_CLIENTES LOOP

    DBMS_OUTPUT.PUT_LINE('NOMBRE:  ' || POR_CADA_CLIENTE.NOMBRE);
    DBMS_OUTPUT.PUT_LINE(' VUELTA NUMERO:  '|| V_CONTADOR);
    V_CONTADOR := V_CONTADOR + 1;
    END LOOP;

END;
/

DECLARE 
    CURSOR C_EVENTO IS
        SELECT * FROM EVENTO;

    V_CONTADOR2 NUMBER:= 1;


BEGIN
    FOR CADA_EVENTO IN C_EVENTO LOOP
    DBMS_OUTPUT.PUT_LINE('NOMBRE:  ' || CADA_EVENTO.NOMBRE);
    DBMS_OUTPUT.PUT_LINE(' VUELTA NUMERO:  '|| V_CONTADOR2);
    V_CONTADOR2 := V_CONTADOR2 + 1;
