--NO_DATA_FOUND
DECLARE

V_EMAIL CLIENTE.EMAIL%TYPE;

BEGIN 
    SELECT EMAIL 
    INTO V_EMAIL
    FROM CLIENTE 
    WHERE CLIENTE_ID = 6;
    
    DBMS_OUTPUT.PUT_LINE('EL CORREO ES: '|| V_EMAIL);

    EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('NO EXISTE EL USUARIO:'); 
END;
/


