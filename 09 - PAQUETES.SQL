--NECESITA LA SPEC DEL PACKAGE
--SE ENCARGA DE DARLE LOS DATOS QUE VA A USAR, NO VA LOGICA AQUI
CREATE OR REPLACE PACKAGE PKG_BOLETERIA
AS
    G_CANTIDAD_ENTRADAS_VENDIDAS NUMBER := 0;
    FUNCTION FN_VERIFICAR_STOCK(
        P_LOCALIDAD_EVENTO_ID IN NUMBER
    ) RETURN NUMBER;

    PROCEDURE SP_VENTA_ENTRADA(
        P_LOCALIDAD_EVENTO_ID IN NUMBER, 
        P_CANTIDAD_ENTRADAS_A_COMPRAR IN NUMBER
    );
END PKG_BOLETERIA;
/

--BODY
CREATE OR REPLACE PACKAGE BODY PKG_BOLETERIA
AS
    FUNCTION FN_VERIFICAR_STOCK(
        P_LOCALIDAD_EVENTO_ID IN NUMBER
    ) RETURN NUMBER

    AS 
        V_STOCK_DISPONIBLE NUMBER;
    BEGIN
        SELECT STOCK_DISPONIBLE 
        INTO V_STOCK_DISPONIBLE
        FROM LOCALIDAD_EVENTO 
        WHERE LOCALIDAD_EVENTO_ID = P_LOCALIDAD_EVENTO_ID;
        RETURN V_STOCK_DISPONIBLE;

    END FN_VERIFICAR_STOCK;



    PROCEDURE SP_VENTA_ENTRADA(
        P_LOCALIDAD_EVENTO_ID IN NUMBER, 
        P_CANTIDAD_ENTRADAS_A_COMPRAR IN NUMBER
    ) 
    AS
        V_STOCK_DISPONIBLE NUMBER;
    BEGIN 
        V_STOCK_DISPONIBLE := FN_VERIFICAR_STOCK(P_LOCALIDAD_EVENTO_ID);

        IF V_STOCK_DISPONIBLE <= 0 THEN 
            RAISE_APPLICATION_ERROR(-2001, 'NO HAY STOCK DISPONIBLE PARA');
        END IF;

        UPDATE LOCALIDAD_EVENTO SET STOCK_DISPONIBLE = STOCK_DISPONIBLE - P_CANTIDAD_ENTRADAS_A_COMPRAR
        WHERE LOCALIDAD_EVENTO_ID = P_LOCALIDAD_EVENTO_ID;


        G_CANTIDAD_ENTRADAS_VENDIDAS := G_CANTIDAD_ENTRADAS_VENDIDAS + P_CANTIDAD_ENTRADAS_A_COMPRAR;
    END SP_VENTA_ENTRADA;
END PKG_BOLETERIA;
/

DECLARE 
    V_STOCK NUMBER;
BEGIN 
    --SE PUEDE IMPRIMIR 
    DBMS_OUTPUT.PUT_LINE('EL STOCK DISPONIBLE ES: ' ||
    PKG_BOLETERIA.FN_VERIFICAR_STOCK(1)); 


    -- SE PUEDE GUARDAR EN UNA VARIABLE 
    V_STOCK := PKG_BOLETERIA.FN_VERIFICAR_STOCK(1);
    DBMS_OUTPUT.PUT_LINE('EL STOCK DISPONIBLE ES: ' || V_STOCK); 


    --EN ESTE CASO NO RETORNA NADA ENTONCES NO SE GUARDA NADA, CASO CONTRARIO SI TUVIERA SE PODRIA HACER
    PKG_BOLETERIA.SP_VENTA_ENTRADA(1,10);
    DBMS_OUTPUT.PUT_LINE('SE VENDIERON ENTRADAS'); 
    DBMS_OUTPUT.PUT_LINE('EL TOTOAL DE ENTRADAS VENDIDAS ES: ' || PKG_BOLETERIA.G_CANTIDAD_ENTRADAS_VENDIDAS); 

   
END;


















